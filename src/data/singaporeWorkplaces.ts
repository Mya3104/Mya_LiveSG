/**
 * Fast search over predefined Singapore workplace hubs and landmarks
 */
export function searchPredefinedWorkplaces(query: string): WorkplaceLocation[] {
  if (!query || !query.trim()) {
    return SINGAPORE_WORKPLACES.slice(0, 8);
  }

  const q = query.toLowerCase().trim();
  return SINGAPORE_WORKPLACES.filter((w) => {
    return (
      w.name.toLowerCase().includes(q) ||
      (w.subtitle && w.subtitle.toLowerCase().includes(q)) ||
      (w.address && w.address.toLowerCase().includes(q)) ||
      (w.area && w.area.toLowerCase().includes(q)) ||
      (w.mrtStation && w.mrtStation.toLowerCase().includes(q))
    );
  });
}

/**
 * Maps any custom location or search text to the closest known Singapore hub ID
 */
export function resolveWorkplaceToHubId(nameOrAddress: string): string {
  const q = nameOrAddress.toLowerCase();

  if (q.includes('changi') || q.includes('expo') || q.includes('aerospace') || q.includes('loyang')) {
    return 'changi_biz';
  }
  if (q.includes('one-north') || q.includes('biopolis') || q.includes('fusionopolis') || q.includes('buona vista') || q.includes('nus') || q.includes('mapletree') || q.includes('pasir panjang') || q.includes('alexandra')) {
    return 'one_north';
  }
  if (q.includes('jurong') || q.includes('tuas') || q.includes('cleantech') || q.includes('ibp') || q.includes('clementi') || q.includes('boon lay')) {
    return 'jurong_lake';
  }
  if (q.includes('woodlands') || q.includes('yishun') || q.includes('sembawang') || q.includes('mandai') || q.includes('causeway')) {
    return 'woodlands_regional';
  }
  if (q.includes('tampines') || q.includes('pasir ris') || q.includes('paya lebar') || q.includes('bedok') || q.includes('punggol')) {
    return 'tampines';
  }
  if (q.includes('raffles') || q.includes('tanjong pagar') || q.includes('telok ayer') || q.includes('ceylon') || q.includes('shenton') || q.includes('maxwell') || q.includes('cbd')) {
    return 'raffles_place';
  }
  // Default to MBFC / Downtown Core
  return 'mbfc';
}
